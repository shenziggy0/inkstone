/**
 * Rendered-text → Markdown-source offset mapping.
 *
 * Markdown source is the single source of truth: a rendered block is a
 * `Decoration.replace` widget whose DOM is disposable. To put the caret at the
 * character the user actually clicked, we align the widget's visible text
 * with the block's raw Markdown. Rendered text is (almost) a subsequence of
 * the source — Markdown markers, fences and attributes are skipped, while
 * visible characters keep their identity — so a forward, scored alignment is
 * enough to recover a source offset for every rendered character.
 *
 * This is deliberately a display-layer concern: it never changes the document,
 * and it is only consulted on pointer interaction with a rendered block.
 */

// Rendered text is a subsequence of the source in document order, so the
// earliest match at/after the cursor is the correct one. A generated glyph
// must never jump the cursor across a long stretch of source, though.
const MAX_GAP = 256;

// Text nodes generated by the renderer, not present in the Markdown source.
// Mapping them would corrupt the alignment of everything after them.
const GENERATED = [
  '.katex',            // KaTeX emits lots of layout-only glyphs
  '.mermaid',          // diagram source is replaced by SVG
  '.diagram',          // sequence / flow source is replaced by SVG
  'svg',
  '.toc',              // [TOC] is generated from the outline
  '.code-language',    // highlight.js language badge
  '.footnote-ref', '.footnote-backref',
  'script', 'style',
  '[data-md-skip]'
].join(', ');

// markdown-it emits formatting newlines between block tags. They are layout
// artifacts, not source content; whitespace inside inline/line contexts is kept.
const LAYOUT_WHITESPACE_PARENTS = new Set([
  'UL', 'OL', 'TABLE', 'THEAD', 'TBODY', 'TFOOT', 'TR', 'BLOCKQUOTE',
  'DIV', 'DL', 'DT', 'DD', 'NAV', 'SECTION', 'ARTICLE', 'FIGURE'
]);

const TEXT_NODE = 3;
const ELEMENT_NODE = 1;

/**
 * For each UTF-16 code unit of `rendered`, return its offset in `source`.
 * Characters that have no counterpart in the source (emoji shortcodes,
 * generated labels, …) are pinned to the current cursor without advancing it,
 * so the following real characters still align correctly.
 */
export function alignSourceOffsets(rendered, source) {
  const offsets = new Array(rendered.length);
  let cursor = 0;
  for (let i = 0; i < rendered.length; i++) {
    const match = source.indexOf(rendered[i], cursor);
    if (match < 0 || match - cursor > MAX_GAP) {
      // Generated glyph (emoji shortcode, entity, generated label): pin it to
      // the current position instead of consuming a far-away source character.
      offsets[i] = Math.min(cursor, source.length);
      continue;
    }
    offsets[i] = match;
    cursor = match + 1;
  }
  return offsets;
}

/**
 * Build a Text-node → source-offsets map for one rendered block.
 * Offsets are relative to the block's start (`widget.from`).
 */
export function buildSourceMap(element, source) {
  const map = new Map();
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let node;
  while ((node = walker.nextNode())) {
    const value = node.nodeValue;
    if (!value) continue;
    const parent = node.parentElement;
    if (!parent || parent.closest(GENERATED)) continue;
    if (!value.trim() && LAYOUT_WHITESPACE_PARENTS.has(parent.tagName)) continue;
    nodes.push(node);
  }
  const offsets = alignSourceOffsets(nodes.map(n => n.nodeValue).join(''), source);
  let cursor = 0;
  for (const text of nodes) {
    map.set(text, offsets.slice(cursor, cursor + text.nodeValue.length));
    cursor += text.nodeValue.length;
  }
  return map;
}

function caretAt(x, y) {
  if (typeof document.caretPositionFromPoint === 'function') {
    const position = document.caretPositionFromPoint(x, y);
    if (position) return { node: position.offsetNode, offset: position.offset };
  }
  if (typeof document.caretRangeFromPoint === 'function') {
    const range = document.caretRangeFromPoint(x, y);
    if (range) return { node: range.startContainer, offset: range.startOffset };
  }
  return null;
}

function offsetOf(node, offset, map, fallback) {
  if (node.nodeType === TEXT_NODE) {
    const offsets = map.get(node);
    if (!offsets || !offsets.length) return fallback;
    return offset < offsets.length ? offsets[offset] : offsets[offsets.length - 1] + 1;
  }
  if (node.nodeType !== ELEMENT_NODE) return fallback;
  // Some browsers return an element plus a child index at a caret boundary.
  const candidates = [node.childNodes[offset], node.childNodes[offset - 1], ...node.childNodes];
  for (const child of candidates) {
    if (!child) continue;
    if (child.nodeType === TEXT_NODE && map.has(child)) return offsetOf(child, 0, map, fallback);
    if (child.nodeType !== ELEMENT_NODE) continue;
    const walker = document.createTreeWalker(child, NodeFilter.SHOW_TEXT);
    let text;
    while ((text = walker.nextNode())) if (map.has(text)) return offsetOf(text, 0, map, fallback);
  }
  return fallback;
}

/** Resolve a viewport point to a source offset inside the block. */
export function sourceOffsetAt(map, x, y, fallback) {
  const caret = caretAt(x, y);
  return caret ? offsetOf(caret.node, caret.offset, map, fallback) : fallback;
}

/** Images have no text node; place the caret on their alt text in the source. */
export function imageSourceOffset(source, alt) {
  if (!alt) return -1;
  const marker = source.indexOf(`![${alt}]`);
  return marker < 0 ? -1 : marker + 2;
}
